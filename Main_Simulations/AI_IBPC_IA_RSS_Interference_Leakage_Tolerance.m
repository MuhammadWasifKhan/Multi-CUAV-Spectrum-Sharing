clc; clear; close all;
% Reproducible function-path setup. Keeps existing CVX installation on path.
projectRoot=fileparts(fileparts(mfilename('fullpath')));
addpath(projectRoot,'-begin');
configure_simulation_paths(projectRoot,'common');
% Modularized from the original repository: function bodies unchanged.
% COMPARISON: Proposed I AI-IBPC versus Proposed II reserved four-case.
% Standalone complete script; same underlying resource AO and SCA as the
% previously supplied flight-time source; only the outer sweep is changed to the common licensed/unlicensed leakage tolerance. Does NOT impose reference-figure values.
% AI-IBPC: integrated four-case interference protection and rate-aware power control;
%          no separate post-protection clipping block and no reserved channels.
% Reserved: raw-interference-triggered dual-band reserved-subchannel search;
%           no pre-search/post-search clipping; protection is candidate feasibility.
% IMPORTANT: each proposed scheme optimizes its OWN trajectory.
% Both start from the same Qinit for fairness. Proposed I uses AI-IBPC in
% its AO trajectory loop; Proposed II uses the Reserved controller in its
% own AO trajectory loop.
area=1000; H=100; U=3; K=6; Ninitial=6; J=10; M=10; Nt=8;
Bsc_lic=180e3; Bsc_un=180e3; N0_dBmHz=-169;
sigma2_lic=10.^((N0_dBmHz+10*log10(Bsc_lic)-30)/10);
sigma2_un=10.^((N0_dBmHz+10*log10(Bsc_un)-30)/10);
Pmax_lic=0.3; Pmax_un_fixed=0.7; P_PBS=2.5; P_WIFI=1;
threshold_lic_dBm=-80; % Licensed protection remains fixed
threshold_list_dBm=-120:10:-70; % Sweep ONLY unlicensed leakage tolerance
P_PBS_j=P_PBS*ones(J,1); P_WIFI_m=P_WIFI*ones(M,1);
c=3e8; f_lic=2e9; f_un=5e9; f_pbs=f_lic; f_wifi=f_un;
n_pbs=3.7; n_wifi=3; sigmaSh_pbs_dB=8; sigmaSh_wifi_dB=6;
A2G=struct('a',9.61,'b',0.16,'etaLoS_dB',1,'etaNLoS_dB',20,...
    'sigmaLoS_dB',4,'sigmaNLoS_dB',6);
useRayleigh=true; useShadow=true; useShadowA2G=true;
MM_iter=10; MM_leakFrac=1; MM_reg_alpha=1e-3; QoS_target=0;
GammaLic=10.^((threshold_lic_dBm-30)/10)*ones(J,1); % Fixed at -80 dBm
GammaUn=[];
w_b=[area/2 area/2]; w_wifi=[area/2 area/2+200];
q_start_all=[120 850;260 180;430 620]; q_end_all=q_start_all;
dt_fixed=5; Tflight=220; Vmax_UAV=5;
STEP_MAX_FIXED=Vmax_UAV*dt_fixed; Dmin_UAV=100;
AO_AP_iter=3; AO_traj_iter=5; alpha_traj=0.30; fd_eps=1;
Nsamp_traj=5; trajSeedBase=77777; dropSeedBase=9000;
NDrops=30; MC=300; % Edit only for desired production Monte Carlo sample size.
reserveLic=(Ninitial+1):J; reserveUn=(Ninitial+1):M;
avgRateHybrid=zeros(NDrops,numel(threshold_list_dBm));
avgRateReserved=zeros(NDrops,numel(threshold_list_dBm));
selectionCounts=zeros(NDrops,numel(threshold_list_dBm));
global AIIBPC_RATE_CALLS AIIBPC_BEAM_CALLS;
AIIBPC_RATE_CALLS=[]; AIIBPC_BEAM_CALLS=[];
fprintf('Matched UNLICENSED leakage-tolerance comparison: AI-IBPC and Four-case Reserved\n');
for drop=1:NDrops
    rng(dropSeedBase+drop,'twister');
    WS=area*rand(K,2); WP=area*rand(J,2); WW=area*rand(M,2);
    Shadow=struct();
    Shadow.pbs_su_dB=sigmaSh_pbs_dB*randn(K,1);
    Shadow.wifi_su_dB=sigmaSh_wifi_dB*randn(K,1);
    Shadow.a2g_su_z=randn(K,1);
    Shadow.a2g_pu_z=randn(J,1);
    Shadow.a2g_wu_z=randn(M,1);
    Sinit=Shadow;
    Sinit.a2g_pu_z=Shadow.a2g_pu_z(1:Ninitial);
    Sinit.a2g_wu_z=Shadow.a2g_wu_z(1:Ninitial);
    % IMPORTANT: Each leakage-tolerance point starts from the same flight-time-specific initialization.
    % No trajectory warm-start is transferred between tolerance points.
    N=round(Tflight/dt_fixed)+1;
    for ti=1:numel(threshold_list_dBm)
        threshold_dBm=threshold_list_dBm(ti);
        % Sweep ONLY the unlicensed-band aggregate interference tolerance.
        % Licensed-band aggregate interference threshold remains fixed at -80 dBm.
        GammaUn=10.^((threshold_dBm-30)/10)*ones(M,1);
        q_hover_all=make_multi_hover_points_closed(q_start_all,WS,area);
        Qhover=build_multi_fly_hover_trajectory(q_start_all,q_hover_all,...
            q_end_all,N,STEP_MAX_FIXED,area);
        if ~check_multi_traj_feasibility(Qhover,q_start_all,q_end_all,...
                STEP_MAX_FIXED,area,Dmin_UAV)
            Qhover=repair_multi_trajectory_cvx(Qhover,area,STEP_MAX_FIXED,...
                q_start_all,q_end_all,Dmin_UAV);
        end
        % Use the same fly-hover-fly initialization for every leakage-tolerance point.
        Qinit=Qhover;
        % Proposed-I outer AO: communication/resource blocks including
        % AI-IBPC are solved first; joint-waypoint SCA is the final block.
        % Proposed I: optimize its own trajectory using AI-IBPC.
        Q_AI=build_multi_traj_AO_qos_bf(Qinit,q_start_all,q_end_all,WS,...
            WP(1:Ninitial,:),WW(1:Ninitial,:),w_b,w_wifi,H,...
            f_lic,f_un,f_pbs,f_wifi,c,A2G,n_pbs,n_wifi,Sinit,...
            P_PBS_j(1:Ninitial),P_WIFI_m(1:Ninitial),...
            sigma2_lic,sigma2_un,GammaLic(1:Ninitial),...
            GammaUn(1:Ninitial),Pmax_lic,Pmax_un_fixed,...
            QoS_target,Bsc_lic,Bsc_un,AO_AP_iter,AO_traj_iter,...
            STEP_MAX_FIXED,alpha_traj,fd_eps,area,Nsamp_traj,Dmin_UAV,...
            trajSeedBase+10000*drop+1000*ti+10,...
            useRayleigh,useShadow,useShadowA2G,Nt,MM_iter,...
            MM_leakFrac,MM_reg_alpha,'prop-pb-mm','AI-IBPC joint AO trajectory');

        % Proposed II: start from the SAME Qinit, but optimize a separate
        % trajectory using the final Reserved-subchannel controller.
        Q_RES=build_multi_traj_AO_reserved(Qinit,q_start_all,q_end_all,WS,...
            WP,WW,w_b,w_wifi,H,f_lic,f_un,f_pbs,f_wifi,c,A2G,n_pbs,n_wifi,Shadow,...
            P_PBS_j,P_WIFI_m,sigma2_lic,sigma2_un,GammaLic,GammaUn,...
            Pmax_lic,Pmax_un_fixed,QoS_target,Bsc_lic,Bsc_un,AO_AP_iter,...
            AO_traj_iter,STEP_MAX_FIXED,alpha_traj,area,Dmin_UAV,...
            trajSeedBase+10000*drop+1000*ti+20,useRayleigh,useShadow,useShadowA2G,...
            Nt,MM_iter,MM_leakFrac,MM_reg_alpha,Ninitial,reserveLic,reserveUn);

        % Diagnostic: verify that each SCA optimizer actually changes Qinit.
        dQ_AI=norm(Q_AI(:)-Qinit(:));
        dQ_RES=norm(Q_RES(:)-Qinit(:));
        fprintf('Drop %d/%d | Gamma=%d dBm | trajectory change: AI-IBPC=%.4f m | Reserved=%.4f m\n',...
            drop,NDrops,threshold_dBm,dQ_AI,dQ_RES);

        sumRateHybrid=0; sumRateReserved=0; selectedConv=0;
        for mc=1:MC
            for n=1:N
                seedNow=12345+100000*drop+1000*mc+n;
                Qslot=squeeze(Q_AI(:,n,:));
                [HL,HU,HP0,HW0,hp,hw]=gen_multi_channels_vec(...
                    Qslot,WS,WP(1:Ninitial,:),WW(1:Ninitial,:),...
                    w_b,w_wifi,H,f_lic,f_un,f_pbs,f_wifi,c,A2G,...
                    n_pbs,n_wifi,Sinit,seedNow,useRayleigh,...
                    useShadow,useShadowA2G,Nt);
                [~,~,~,~,~,dd]=eval_slot_multi_qos_bf(...
                    Qslot,WS,WP(1:Ninitial,:),WW(1:Ninitial,:),...
                    w_b,w_wifi,H,f_lic,f_un,f_pbs,f_wifi,c,A2G,...
                    n_pbs,n_wifi,Sinit,P_PBS_j(1:Ninitial),...
                    P_WIFI_m(1:Ninitial),sigma2_lic,sigma2_un,...
                    GammaLic(1:Ninitial),GammaUn(1:Ninitial),...
                    Pmax_lic,Pmax_un_fixed,QoS_target,Bsc_lic,...
                    Bsc_un,AO_AP_iter,seedNow,useRayleigh,useShadow,...
                    useShadowA2G,Nt,MM_iter,MM_leakFrac,...
                    MM_reg_alpha,'prop-pb-mm',0,true);
                raw=dd.rawTx;
                [~,~,HPextra,HWextra]=gen_multi_channels_vec(...
                    Qslot,WS,WP,WW,w_b,w_wifi,H,f_lic,f_un,...
                    f_pbs,f_wifi,c,A2G,n_pbs,n_wifi,Shadow,...
                    seedNow+250000,useRayleigh,useShadow,useShadowA2G,Nt);
                HP=cell(U,J); HW=cell(U,M);
                HP(:,1:Ninitial)=HP0; HW(:,1:Ninitial)=HW0;
                HP(:,reserveLic)=HPextra(:,reserveLic);
                HW(:,reserveUn)=HWextra(:,reserveUn);
                rateFn=@(tx)diagnostic_tx_rate(tx,HL,HU,hp,hw,...
                    P_PBS_j,P_WIFI_m,sigma2_lic,sigma2_un,Bsc_lic,Bsc_un);
                % Proposed I: integrated AI-IBPC four-case controller.
                % The controller itself enforces PU/WU protection while selecting
                % rate-aware power adjustments. No separate protection/clipping
                % block is applied after AI-IBPC.
                [txFinal,aiibpcStats]=ai_ibpc_integrated_four_case_rateaware(...
                    raw,HP,HW,GammaLic,GammaUn,...
                    Pmax_lic,Pmax_un_fixed,rateFn);
                selectedConv=selectedConv+double(aiibpcStats.caseId==3);
                [checkL,checkU]=pure_check(txFinal,HP,HW,...
                    GammaLic,GammaUn,Pmax_lic,Pmax_un_fixed);
                assert(max(checkL,checkU)<=1+1e-5,...
                    'AI-IBPC allocation violates protection');
                sumRateHybrid=sumRateHybrid+rateFn(txFinal);

                % Proposed II: evaluate on its OWN Reserved-optimized trajectory.
                QslotRes=squeeze(Q_RES(:,n,:));
                [txReserved,rateReserved]=eval_slot_reserved_final(QslotRes,WS,WP,WW,...
                    w_b,w_wifi,H,f_lic,f_un,f_pbs,f_wifi,c,A2G,n_pbs,n_wifi,Shadow,...
                    P_PBS_j,P_WIFI_m,sigma2_lic,sigma2_un,GammaLic,GammaUn,...
                    Pmax_lic,Pmax_un_fixed,QoS_target,Bsc_lic,Bsc_un,AO_AP_iter,...
                    seedNow,useRayleigh,useShadow,useShadowA2G,Nt,MM_iter,...
                    MM_leakFrac,MM_reg_alpha,Ninitial,reserveLic,reserveUn);
                sumRateReserved=sumRateReserved+rateReserved;
            end
        end
        avgRateHybrid(drop,ti)=sumRateHybrid/(MC*N*1e6);
        avgRateReserved(drop,ti)=sumRateReserved/(MC*N*1e6);
        selectionCounts(drop,ti)=selectedConv;
        fprintf('Drop %d/%d | Gamma=%d dBm | AI-IBPC=%.5f | Reserved=%.5f Mbps\n',...
            drop,NDrops,threshold_dBm,avgRateHybrid(drop,ti),...
            avgRateReserved(drop,ti));
        save('Proposed_I_II_LeakageTolerance_Checkpoint.mat',...
            'avgRateHybrid','avgRateReserved','selectionCounts',...
            'threshold_list_dBm','Tflight','Pmax_un_fixed','drop','ti','MC','NDrops');
    end
end
meanHybrid=mean(avgRateHybrid,1);
meanReserved=mean(avgRateReserved,1);
Results=table(threshold_list_dBm(:),meanHybrid(:),meanReserved(:),...
    'VariableNames',{'LeakageTolerance_dBm','AI_IBPC_Mbps',...
    'FourCase_Reserved_Mbps'});
disp(Results);
writetable(Results,'Proposed_I_II_LeakageTolerance_Comparison.csv');
save('Proposed_I_II_LeakageTolerance_Comparison.mat','Results',...
    'avgRateHybrid','avgRateReserved','selectionCounts','threshold_list_dBm','Tflight','Pmax_un_fixed','MC','NDrops');
figure('Color','w','Position',[100 100 620 470]); hold on;
plot(threshold_list_dBm,meanHybrid,'-o','Color',[0 0.4470 0.7410],...
    'LineWidth',2,'MarkerSize',8,'MarkerFaceColor','w');
plot(threshold_list_dBm,meanReserved,'-d','Color',[0.8500 0.3250 0.0980],...
    'LineWidth',2,'MarkerSize',8,'MarkerFaceColor','w');
ax=gca;
set(ax,'FontName','Times New Roman','FontSize',16,...
    'FontWeight','normal','LineWidth',1.2,...
    'Position',[0.13 0.13 0.84 0.68]);
grid on; set(ax,'GridLineStyle',':','GridAlpha',0.30);
xlabel('Unlicensed interference leakage tolerance (dBm)'); ylabel('Average sum rate (Mbps)');
legend({'Proposed I (AI-IBPC)',...
    'Proposed II (Four-case Reserved)'},...
    'Location','northoutside','Orientation','horizontal',...
    'FontName','Times New Roman','FontSize',11,'Box','on');
xticks(threshold_list_dBm); xlim([threshold_list_dBm(1) threshold_list_dBm(end)]);
exportgraphics(gcf,'Proposed_I_II_LeakageTolerance_Comparison.png','Resolution',300);

